class ContactMessageRequest(BaseModel):
    name: str
    email: str
    subject: str
    message: str
    phone: Optional[str] = None

class IssueReportRequest(BaseModel):
    category: Optional[str] = "General"
    severity: Optional[str] = "Medium"
    description: str
    attachments: Optional[List[str]] = []
    user_email: Optional[str] = None

def _dispatch_admin_notification(subject: str, html_content: str, text_content: str):
    try:
        success, reason = send_transactional_email_detailed(
            to_email=ADMIN_CONTACT_EMAIL,
            subject=subject,
            body_html=html_content,
            body_text=text_content
        )
        if success:
            logger.info(f"[SUPPORT] Complaint/inquiry email successfully forwarded to {ADMIN_CONTACT_EMAIL}")
        else:
            logger.warning(f"[SUPPORT] Could not forward email to {ADMIN_CONTACT_EMAIL}: {reason}")
    except Exception as e:
        logger.error(f"[SUPPORT] Error dispatching email to {ADMIN_CONTACT_EMAIL}: {e}")

