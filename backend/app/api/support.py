logger = logging.getLogger("app.api.support")

router = APIRouter(prefix="/support", tags=["Support & Complaints"])

ADMIN_CONTACT_EMAIL = "athiya160@gmail.com"
ADMIN_CONTACT_PHONE = "9986474220"

def get_db():
    db = SessionLocal()
