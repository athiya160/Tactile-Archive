@router.get("/faqs")
def get_faqs():
    """Returns the list of frequently asked questions."""
    return FAQS_DATA

@router.get("/faqs/search")
def search_faqs(q: str = ""):
    """Search FAQs by query string."""
    if not q:
        return FAQS_DATA
    query_lower = q.lower()
    return [
        faq for faq in FAQS_DATA
        if query_lower in faq["question"].lower() or query_lower in faq["answer"].lower()
    ]
