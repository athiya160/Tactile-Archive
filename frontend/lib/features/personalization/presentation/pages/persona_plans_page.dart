/// Supported Education Tracks
enum EducationTrack {
  class10, // 10th Standard / Secondary (CBSE / ICSE / State)
  puc,     // Pre-University (1st & 2nd PU / 11th & 12th)
  college, // College & University Degree (B.Tech, B.Sc, B.Com, BCA - Sem 1-8)
  competitive, // Competitive Exams (NEET, JEE, UPSC, CA)
}

/// Data model for an uploaded printed / handwritten physical notebook
class PrintedNotebook {
  final String id;
  final String title;
  final String subject;
  final String trackName;
  final String termOrSemester;
  final String unitOrTopic;
  final String authorOrProf;
  final int pageCount;
  final String uploadDate;
  final String uploadType; // 'Camera Scan' or 'PDF Document'
  final Color badgeColor;
  final List<String> keyFormulas;
  final List<String> aiSummaries;
  final List<String> autoGeneratedTasks;

  PrintedNotebook({
    required this.id,
    required this.title,
    required this.subject,
    required this.trackName,
    required this.termOrSemester,
    required this.unitOrTopic,
    this.authorOrProf = 'Self / Class Notes',
    required this.pageCount,
    required this.uploadDate,
    this.uploadType = 'Camera Scan',
    required this.badgeColor,
    required this.keyFormulas,
    required this.aiSummaries,
    required this.autoGeneratedTasks,
  });
}

/// Data model for an academic study task
class StudyTask {
  final String id;
  final String title;
  final String subject;
  final String termOrSemester;
  final String dueDate;
  bool isCompleted;
  final String? sourceNotebook;

  StudyTask({
    required this.id,
    required this.title,
    required this.subject,
    required this.termOrSemester,
    required this.dueDate,
    this.isCompleted = false,
    this.sourceNotebook,
  });
}

/// Data model for an upcoming exam
class SemesterExam {
  final String id;
  final String subject;
  final String termOrSemester;
  final String date;
  final String daysLeft;
  final String time;
  final String venue;
  final int weightagePercent;

  SemesterExam({
    required this.id,
    required this.subject,
    required this.termOrSemester,
    required this.date,
    required this.daysLeft,
    this.time = '10:00 AM - 1:00 PM',
    this.venue = 'Main Exam Hall',
    this.weightagePercent = 40,
  });
}

/// Data model for a course subject
class SubjectCourse {
  final String id;
  final String name;
  final String code;
  final String termOrSemester;
  double progress;
  String percent;
  final int creditsOrMarks;
  final String instructor;
  final Color accentColor;

  SubjectCourse({
    required this.id,
    required this.name,
    required this.code,
    required this.termOrSemester,
    required this.progress,
    required this.percent,
    this.creditsOrMarks = 100,
    this.instructor = 'Subject Faculty',
    required this.accentColor,
  });
}

