  void _detectInitialProfile() {
    final rawCourse = ApiService.studentDegree ?? '';
    final rawSemester = ApiService.studentSemester ?? '';

    if (rawCourse.toLowerCase().contains('10th') || rawCourse.toLowerCase().contains('class 10')) {
      _selectedTrack = EducationTrack.class10;
      _selectedStream = _streamsByTrack[EducationTrack.class10]!.first;
      _selectedTerm = _termsByTrack[EducationTrack.class10]!.first;
    } else if (rawCourse.toLowerCase().contains('pu') || rawCourse.toLowerCase().contains('11th') || rawCourse.toLowerCase().contains('12th')) {
      _selectedTrack = EducationTrack.puc;
      _selectedStream = _streamsByTrack[EducationTrack.puc]!.first;
      _selectedTerm = _termsByTrack[EducationTrack.puc]![1]; // 2nd PU Midterm
