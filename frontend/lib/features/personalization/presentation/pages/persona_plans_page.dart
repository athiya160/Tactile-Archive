      _selectedTrack = EducationTrack.college;
      _selectedStream = (rawCourse.isNotEmpty) ? rawCourse : 'Computer Science & Engineering (B.Tech)';
      _selectedTerm = (rawSemester.isNotEmpty) ? rawSemester : 'Semester 4';
